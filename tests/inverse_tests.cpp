#include <ping_pong/inverse.hpp>
#include <cstdlib>
#include <iostream>
#include <limits>

namespace {
int checks = 0;
void check(bool ok, const char* label) {
    ++checks;
    if (!ok) { std::cerr << "FAIL: " << label << '\n'; std::exit(1); }
}
bool close(double a, double b, double tol = 1e-8) {
    return std::abs(a-b) <= tol * std::max(1.0, std::abs(b));
}
double norm(ping_pong::Vec3 v) { return std::hypot(v.x, v.y, v.z); }
template<class F> void invalid(F f) {
    try { f(); } catch (const std::invalid_argument&) { check(true, "invalid rejected"); return; }
    check(false, "invalid input accepted");
}
}
int main() {
    using namespace ping_pong;
    InverseOptions o;
    o.min_time = o.max_time = 2;
    o.position_scale = o.velocity_scale = 1;
    o.max_launch_speed = 100;
    // Independent fixed-time solution: J=(2u-10)^2+(u-1)^2.
    auto r = solve_inverse({}, {{10,0,0},{1,0,0}}, {}, o);
    check(close(r.initial_velocity.x, 4.2), "analytic weighted compromise");
    check(close(r.cost, 12.8), "analytic cost");
    check(close(r.position_error.x, -1.6), "signed position residual");
    check(close(r.velocity_error.x, 3.2), "signed velocity residual");
    o.position_scale = 0.5;
    r = solve_inverse({}, {{10,0,0},{1,0,0}}, {}, o);
    check(close(r.initial_velocity.x, 81.0/17), "unequal physical scales");
    o.max_launch_speed = 2;
    r = solve_inverse({}, {{10,10,0},{1,1,0}}, {}, o);
    check(close(norm(r.initial_velocity), 2), "speed cap active");
    check(close(r.initial_velocity.x, std::sqrt(2.0)), "speed projection direction");
    o.max_launch_speed = 0;
    r = solve_inverse({}, {{10,0,0},{1,0,0}}, {}, o);
    check(norm(r.initial_velocity) == 0, "zero launch speed supported");

    // Reachable 3D endpoints generated by the independently tested forward model.
    o = {};
    const Vec3 start{0.2,-0.3,1.1}, gravity{0,0,-9.81};
    for (int i=0; i<12; ++i) {
        double t = 0.123 + i * 0.157;
        Vec3 v{1.0 + i*0.2, -0.5, 2.0};
        State target = advance({start,v}, gravity, std::chrono::duration<double>{t});
        r = solve_inverse(start, target, gravity, o);
        check(r.position_error_norm < 1e-7 && r.velocity_error_norm < 1e-7,
              "reachable endpoint recovered");
        check(close(r.flight_time, t, 1e-7), "flight time recovered");
        const auto replay = advance({start,r.initial_velocity}, gravity,
                                   std::chrono::duration<double>{r.flight_time});
        check(close(replay.position.z, r.arrival.position.z), "forward replay");
    }
    // Zero acceleration, impossible to match position and rest together.
    o.min_time = 0.1; o.max_time = 2;
    o.position_scale = o.velocity_scale = 1;
    r = solve_inverse({}, {{1,0,0},{}}, {}, o);
    check(r.flight_time == 2, "upper time boundary optimum");
    check(close(r.cost, 0.2), "incompatible endpoint compromise");
    r = solve_inverse({}, {{-1,0,0},{1,0,0}}, {}, o);
    check(r.flight_time == 0.1, "lower time boundary optimum");

    // Compare flexible search with a much denser independent time enumeration.
    o = {}; o.max_launch_speed = 3;
    const State target{{2,0.4,0.8},{4,-0.2,-3}};
    r = solve_inverse(start, target, gravity, o);
    InverseOptions fixed = o;
    double dense_best = std::numeric_limits<double>::infinity();
    for (int i=0; i<=20000; ++i) {
        fixed.min_time = fixed.max_time = o.min_time + (o.max_time-o.min_time)*i/20000;
        dense_best = std::min(dense_best, solve_inverse(start,target,gravity,fixed).cost);
    }
    check(r.cost <= dense_best + 1e-7, "search agrees with dense time oracle");
    check(norm(r.initial_velocity) <= 3 + 1e-12, "flexible search respects speed cap");
    check(r.flight_time >= o.min_time && r.flight_time <= o.max_time, "time bounds");
    check(close(r.cost, std::pow(r.position_error_norm/o.position_scale,2)
                       + std::pow(r.velocity_error_norm/o.velocity_scale,2)), "reported cost");

    for (int field=0; field<9; ++field) {
        auto bad = o;
        switch(field) {
        case 0: bad.min_time = 0; break;
        case 1: bad.max_time = bad.min_time/2; break;
        case 2: bad.max_launch_speed = -1; break;
        case 3: bad.position_scale = 0; break;
        case 4: bad.velocity_scale = -1; break;
        case 5: bad.time_intervals = 1; break;
        case 6: bad.refinement_iterations = 0; break;
        case 7: bad.min_time = std::numeric_limits<double>::quiet_NaN(); break;
        case 8: bad.max_time = std::numeric_limits<double>::infinity(); break;
        }
        invalid([&]{ (void)solve_inverse(start,target,gravity,bad); });
    }
    invalid([&]{ (void)solve_inverse({NAN,0,0},target); });
    invalid([&]{ (void)solve_inverse(start,{{},{0,INFINITY,0}}); });
    invalid([&]{ (void)solve_inverse(start,target,{0,0,NAN}); });
    std::cout << checks << " inverse checks passed\n";
}
